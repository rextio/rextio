"""Sealed offline Cargo dependency workspace for the bounded Full C6 profile.

The collector consumes an owner-prepared ``cargo vendor --locked`` directory
without following links, verifies it against one exact ``Cargo.lock``
``CargoSourcesIdentity``, and retains immutable file bytes for a later private
materialization.  It never executes Cargo and never authorizes a build or
distribution by itself.
"""

from __future__ import annotations

import hashlib
import hmac
import json
import os
import re
import secrets
import stat
import tomllib
import unicodedata
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath, PureWindowsPath
from typing import SupportsIndex

from rextio.build.toolchain_identity import (
    CargoSourceIdentity,
    CargoSourcesIdentity,
    ToolchainIdentityError,
    capture_cargo_sources,
)


FULL_C6_CARGO_WORKSPACE_DOMAIN = "rextio.full-c6-cargo-dependency-workspace.v1"
FULL_C6_CARGO_VENDOR_TREE_DOMAIN = "rextio.full-c6-cargo-vendor-tree.v1"
FULL_C6_CARGO_PACKAGE_DOMAIN = "rextio.full-c6-cargo-vendor-package.v1"
FULL_C6_CARGO_EXECUTOR_CONFIG = ".cargo/config.toml"
FULL_C6_CARGO_VENDOR_PREFIX = "vendor"
FULL_C6_CARGO_LAYOUT_DEFAULT = "cargo-vendor-default-v1"
FULL_C6_CARGO_LAYOUT_VERSIONED = "cargo-vendor-versioned-dirs-v1"
FULL_C6_CARGO_EXECUTOR_CONFIG_BYTES = (
    b"# Generated by Rextio Full C6. Do not edit.\n"
    b"[source.crates-io]\n"
    b'replace-with = "rextio-vendored-sources"\n\n'
    b"[source.rextio-vendored-sources]\n"
    b'directory = "vendor"\n\n'
    b"[net]\n"
    b"offline = true\n"
)

MAX_FULL_C6_CARGO_PACKAGES = 256
MAX_FULL_C6_CARGO_TREE_ENTRIES = 16_384
MAX_FULL_C6_CARGO_FILES = 12_288
MAX_FULL_C6_CARGO_DEPTH = 16
MAX_FULL_C6_CARGO_PATH_CHARS = 512
MAX_FULL_C6_CARGO_FILE_BYTES = 64 * 1024 * 1024
MAX_FULL_C6_CARGO_TOTAL_BYTES = 512 * 1024 * 1024
MAX_FULL_C6_CARGO_CHECKSUM_BYTES = 8 * 1024 * 1024
MAX_FULL_C6_CARGO_MANIFEST_BYTES = 2 * 1024 * 1024

_SHA256 = re.compile(r"^[0-9a-f]{64}$")
_PACKAGE_DIRECTORY = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._+-]{0,255}$")
_ALLOWED_REGISTRY_SOURCES = frozenset(
    {
        "registry+https://github.com/rust-lang/crates.io-index",
        "sparse+https://index.crates.io/",
    }
)
_LICENSE_BASENAMES = ("LICENSE", "LICENCE", "COPYING", "NOTICE")
_DIRECTORY_MODE = 0o755
_FILE_MODES = frozenset({0o644, 0o755})
_SEAL_KEY = secrets.token_bytes(32)


class FullC6CargoWorkspaceError(RuntimeError):
    """The Cargo vendor tree is unsafe, incomplete, stale, or unsupported."""


@dataclass(frozen=True, slots=True)
class FullC6CargoWorkspaceEntry:
    """One canonical directory or exact regular-file executor identity."""

    logical_name: str
    kind: str
    sha256: str | None
    size: int
    mode: int

    def __post_init__(self) -> None:
        _validate_logical_name(self.logical_name)
        if self.kind not in {"directory", "file"}:
            raise ValueError("Full C6 Cargo workspace entry kind is invalid")
        if self.kind == "directory":
            if self.sha256 is not None or self.size != 0 or self.mode != _DIRECTORY_MODE:
                raise ValueError("Full C6 Cargo workspace directory is noncanonical")
            return
        if type(self.sha256) is not str or _SHA256.fullmatch(self.sha256) is None:
            raise ValueError("Full C6 Cargo workspace file SHA-256 is invalid")
        if (
            type(self.size) is not int
            or isinstance(self.size, bool)
            or not 0 <= self.size <= MAX_FULL_C6_CARGO_FILE_BYTES
            or self.mode not in _FILE_MODES
        ):
            raise ValueError("Full C6 Cargo workspace file identity is invalid")

    @property
    def executable(self) -> bool:
        """Whether the exact captured mode marks this source file executable."""
        return self.kind == "file" and self.mode == 0o755

    def to_dict(self) -> dict[str, object]:
        """Return the path-sanitized exact tree identity."""
        return {
            "logical_name": self.logical_name,
            "kind": self.kind,
            "sha256": self.sha256,
            "size": self.size,
            "mode": self.mode,
        }


@dataclass(frozen=True, slots=True)
class FullC6CargoPackageReceipt:
    """One Cargo.lock package matched to one complete vendor directory."""

    package: CargoSourceIdentity
    directory: str
    checksum_manifest_sha256: str
    file_set_sha256: str
    cargo_toml: str
    metadata_files: tuple[str, ...]

    def __post_init__(self) -> None:
        if type(self.package) is not CargoSourceIdentity:
            raise TypeError("Full C6 Cargo package source identity is invalid")
        if self.directory not in {
            self.package.name,
            f"{self.package.name}-{self.package.version}",
        }:
            raise ValueError("Full C6 Cargo package directory is noncanonical")
        if _PACKAGE_DIRECTORY.fullmatch(self.directory) is None:
            raise ValueError("Full C6 Cargo package directory is invalid")
        if (
            _SHA256.fullmatch(self.checksum_manifest_sha256) is None
            or _SHA256.fullmatch(self.file_set_sha256) is None
        ):
            raise ValueError("Full C6 Cargo package digest is invalid")
        expected_manifest = f"vendor/{self.directory}/Cargo.toml"
        if self.cargo_toml != expected_manifest:
            raise ValueError("Full C6 Cargo package manifest identity is invalid")
        if (
            type(self.metadata_files) is not tuple
            or not self.metadata_files
            or self.metadata_files != tuple(sorted(self.metadata_files, key=str.casefold))
            or len({item.casefold() for item in self.metadata_files})
            != len(self.metadata_files)
            or self.cargo_toml not in self.metadata_files
        ):
            raise ValueError("Full C6 Cargo package metadata identities are invalid")
        for logical_name in self.metadata_files:
            _validate_logical_name(logical_name)
            if not PurePosixPath(logical_name).is_relative_to(
                PurePosixPath("vendor") / self.directory
            ):
                raise ValueError("Full C6 Cargo package metadata escapes its directory")

    @property
    def digest(self) -> str:
        """Return the exact package-to-vendor projection digest."""
        return _sha256({"domain": FULL_C6_CARGO_PACKAGE_DOMAIN, **self._payload()})

    def _payload(self) -> dict[str, object]:
        return {
            "package": self.package.to_dict(),
            "directory": self.directory,
            "checksum_manifest_sha256": self.checksum_manifest_sha256,
            "file_set_sha256": self.file_set_sha256,
            "cargo_toml": self.cargo_toml,
            "metadata_files": list(self.metadata_files),
        }

    def to_dict(self) -> dict[str, object]:
        """Return the complete non-authorizing package receipt."""
        return {**self._payload(), "digest": self.digest}


@dataclass(frozen=True, slots=True)
class FullC6CargoDependencyWorkspaceReceipt:
    """Process-sealed exact dependency workspace and executor projection."""

    cargo_sources: CargoSourcesIdentity
    packages: tuple[FullC6CargoPackageReceipt, ...]
    vendor_layout: str
    vendor_entries: tuple[FullC6CargoWorkspaceEntry, ...]
    vendor_tree_sha256: str
    executor_config: FullC6CargoWorkspaceEntry
    metadata_files: tuple[str, ...]
    _cargo_lock_payload: bytes = field(repr=False)
    _file_payloads: tuple[bytes, ...] = field(repr=False)
    _transaction_seal: bytes = field(repr=False)
    domain: str = FULL_C6_CARGO_WORKSPACE_DOMAIN
    scope: str = "owner-prepared-cargo-vendor-locked-crates-io-v1"
    complete_for_scope: bool = True
    authorizes_build: bool = False
    authorizes_distribution: bool = False

    def __post_init__(self) -> None:
        _validate_receipt_shape(self)
        if type(self._transaction_seal) is not bytes or not hmac.compare_digest(
            self._transaction_seal,
            _receipt_seal(self),
        ):
            raise ValueError("Full C6 Cargo workspace seal is invalid")

    def __copy__(self) -> object:
        raise TypeError("Full C6 Cargo workspace receipt cannot be copied")

    def __deepcopy__(self, _memo: object) -> object:
        raise TypeError("Full C6 Cargo workspace receipt cannot be copied")

    def __reduce__(self) -> str | tuple[object, ...]:
        raise TypeError("Full C6 Cargo workspace receipt cannot be serialized")

    def __reduce_ex__(self, _protocol: SupportsIndex) -> str | tuple[object, ...]:
        raise TypeError("Full C6 Cargo workspace receipt cannot be serialized")

    def __getstate__(self) -> object:
        raise TypeError("Full C6 Cargo workspace receipt cannot be serialized")

    @property
    def executor_projection(self) -> tuple[FullC6CargoWorkspaceEntry, ...]:
        """Return the exact config + vendor tree the executor must freeze."""
        cargo_directory = FullC6CargoWorkspaceEntry(
            logical_name=".cargo",
            kind="directory",
            sha256=None,
            size=0,
            mode=_DIRECTORY_MODE,
        )
        return tuple(
            sorted(
                (*self.vendor_entries, cargo_directory, self.executor_config),
                key=lambda item: (item.logical_name, item.kind),
            )
        )

    @property
    def digest(self) -> str:
        """Return the public semantic receipt digest, excluding retained bytes."""
        return _sha256(self._payload())

    def _payload(self) -> dict[str, object]:
        return {
            "domain": FULL_C6_CARGO_WORKSPACE_DOMAIN,
            "scope": self.scope,
            "complete_for_scope": True,
            "authorizes_build": False,
            "authorizes_distribution": False,
            "cargo_sources": self.cargo_sources.to_dict(),
            "packages": [item.to_dict() for item in self.packages],
            "vendor_layout": self.vendor_layout,
            "vendor_tree_sha256": self.vendor_tree_sha256,
            "vendor_entries": [item.to_dict() for item in self.vendor_entries],
            "executor_config": self.executor_config.to_dict(),
            "executor_projection": [item.to_dict() for item in self.executor_projection],
            "metadata_files": list(self.metadata_files),
        }

    def to_dict(self) -> dict[str, object]:
        """Return only safe identities; retained source bytes never serialize."""
        return {**self._payload(), "digest": self.digest}

    def metadata_payloads(self) -> tuple[tuple[str, bytes], ...]:
        """Return immutable Cargo.toml/license bytes for later policy and SBOM work."""
        validate_full_c6_cargo_dependency_workspace_receipt(self)
        payload_by_name = dict(zip(_file_names(self), self._file_payloads, strict=True))
        return tuple((name, payload_by_name[name]) for name in self.metadata_files)


@dataclass(frozen=True, slots=True)
class _CapturedTree:
    entries: tuple[FullC6CargoWorkspaceEntry, ...]
    payloads: tuple[bytes, ...]


def compute_full_c6_cargo_vendor_tree_sha256(vendor_root: Path | str) -> str:
    """Compute the deterministic bounded vendor tree pin without authorizing it."""
    captured = _capture_stable_vendor_tree(Path(vendor_root))
    return _vendor_tree_digest(captured.entries)


def collect_full_c6_cargo_dependency_workspace(
    *,
    vendor_root: Path | str,
    cargo_lock: Path | str,
    cargo_sources: CargoSourcesIdentity,
    expected_vendor_tree_sha256: str,
) -> FullC6CargoDependencyWorkspaceReceipt:
    """Verify and seal one exact owner-prepared ``cargo vendor --locked`` tree."""
    if type(cargo_sources) is not CargoSourcesIdentity:
        raise FullC6CargoWorkspaceError("Cargo source identity is invalid")
    if (
        type(expected_vendor_tree_sha256) is not str
        or _SHA256.fullmatch(expected_vendor_tree_sha256) is None
    ):
        raise FullC6CargoWorkspaceError("Cargo vendor tree pin is invalid")
    try:
        rebuilt_sources = capture_cargo_sources(
            cargo_lock,
            root_package=cargo_sources.root_package,
            logical_name=cargo_sources.lock_file.logical_name,
        )
    except (ToolchainIdentityError, TypeError, ValueError) as exc:
        raise FullC6CargoWorkspaceError("Cargo.lock source identity could not be rebuilt") from exc
    if not hmac.compare_digest(rebuilt_sources.digest, cargo_sources.digest):
        raise FullC6CargoWorkspaceError("Cargo.lock differs from its exact source identity")
    cargo_lock_payload = _capture_cargo_lock_payload(
        Path(cargo_lock),
        rebuilt_sources,
    )
    if not rebuilt_sources.packages or len(rebuilt_sources.packages) > MAX_FULL_C6_CARGO_PACKAGES:
        raise FullC6CargoWorkspaceError("Cargo dependency package count is outside scope")
    if any(item.source not in _ALLOWED_REGISTRY_SOURCES for item in rebuilt_sources.packages):
        raise FullC6CargoWorkspaceError("Cargo dependency source is not a supported registry")
    name_versions = {(item.name, item.version) for item in rebuilt_sources.packages}
    if len(name_versions) != len(rebuilt_sources.packages):
        raise FullC6CargoWorkspaceError("Cargo package name/version is ambiguous across registries")

    captured = _capture_stable_vendor_tree(Path(vendor_root))
    vendor_tree_sha256 = _vendor_tree_digest(captured.entries)
    if not hmac.compare_digest(vendor_tree_sha256, expected_vendor_tree_sha256):
        raise FullC6CargoWorkspaceError("Cargo vendor tree digest differs from config pin")
    payload_by_name = dict(zip(_file_names_from_entries(captured.entries), captured.payloads, strict=True))
    vendor_layout, packages = _validate_packages(
        rebuilt_sources.packages,
        captured.entries,
        payload_by_name,
    )
    metadata_files = tuple(
        sorted(
            {name for package in packages for name in package.metadata_files},
            key=str.casefold,
        )
    )
    config_entry = FullC6CargoWorkspaceEntry(
        logical_name=FULL_C6_CARGO_EXECUTOR_CONFIG,
        kind="file",
        sha256=hashlib.sha256(FULL_C6_CARGO_EXECUTOR_CONFIG_BYTES).hexdigest(),
        size=len(FULL_C6_CARGO_EXECUTOR_CONFIG_BYTES),
        mode=0o644,
    )
    file_payloads = (FULL_C6_CARGO_EXECUTOR_CONFIG_BYTES, *captured.payloads)
    provisional = FullC6CargoDependencyWorkspaceReceipt.__new__(
        FullC6CargoDependencyWorkspaceReceipt
    )
    object.__setattr__(provisional, "cargo_sources", rebuilt_sources)
    object.__setattr__(provisional, "packages", packages)
    object.__setattr__(provisional, "vendor_layout", vendor_layout)
    object.__setattr__(provisional, "vendor_entries", captured.entries)
    object.__setattr__(provisional, "vendor_tree_sha256", vendor_tree_sha256)
    object.__setattr__(provisional, "executor_config", config_entry)
    object.__setattr__(provisional, "metadata_files", metadata_files)
    object.__setattr__(provisional, "_cargo_lock_payload", cargo_lock_payload)
    object.__setattr__(provisional, "_file_payloads", file_payloads)
    object.__setattr__(provisional, "domain", FULL_C6_CARGO_WORKSPACE_DOMAIN)
    object.__setattr__(
        provisional,
        "scope",
        "owner-prepared-cargo-vendor-locked-crates-io-v1",
    )
    object.__setattr__(provisional, "complete_for_scope", True)
    object.__setattr__(provisional, "authorizes_build", False)
    object.__setattr__(provisional, "authorizes_distribution", False)
    object.__setattr__(provisional, "_transaction_seal", b"")
    seal = _receipt_seal(provisional)
    return FullC6CargoDependencyWorkspaceReceipt(
        cargo_sources=rebuilt_sources,
        packages=packages,
        vendor_layout=vendor_layout,
        vendor_entries=captured.entries,
        vendor_tree_sha256=vendor_tree_sha256,
        executor_config=config_entry,
        metadata_files=metadata_files,
        _cargo_lock_payload=cargo_lock_payload,
        _file_payloads=file_payloads,
        _transaction_seal=seal,
    )


def validate_full_c6_cargo_dependency_workspace_receipt(
    receipt: FullC6CargoDependencyWorkspaceReceipt,
) -> bool:
    """Revalidate the process seal, retained bytes, and exact frozen projection."""
    if type(receipt) is not FullC6CargoDependencyWorkspaceReceipt:
        return False
    try:
        _validate_receipt_shape(receipt)
        expected = _receipt_seal(receipt)
    except (TypeError, ValueError, FullC6CargoWorkspaceError):
        return False
    return hmac.compare_digest(receipt._transaction_seal, expected)


def _validated_full_c6_cargo_lock_payload(
    receipt: FullC6CargoDependencyWorkspaceReceipt,
) -> bytes:
    """Return a fresh immutable lock payload only after full receipt validation."""
    if not validate_full_c6_cargo_dependency_workspace_receipt(receipt):
        raise FullC6CargoWorkspaceError("Cargo dependency workspace receipt is stale")
    return memoryview(receipt._cargo_lock_payload).tobytes()


def materialize_full_c6_cargo_dependency_workspace(
    receipt: FullC6CargoDependencyWorkspaceReceipt,
    destination: Path | str,
) -> tuple[FullC6CargoWorkspaceEntry, ...]:
    """Materialize exact retained bytes into one fresh no-follow executor tree."""
    if not validate_full_c6_cargo_dependency_workspace_receipt(receipt):
        raise FullC6CargoWorkspaceError("Cargo dependency workspace receipt is stale")
    destination_path = Path(destination)
    parent = destination_path.parent
    name = destination_path.name
    if not name or name in {".", ".."}:
        raise FullC6CargoWorkspaceError("Cargo materialization destination is invalid")
    _validate_segment(name)
    directory_flag = getattr(os, "O_DIRECTORY", 0)
    nofollow = getattr(os, "O_NOFOLLOW", 0)
    if not directory_flag or not nofollow:
        raise FullC6CargoWorkspaceError("no-follow directory operations are unavailable")
    parent_fd = _open_directory_path_no_follow(parent)
    root_fd: int | None = None
    opened: dict[tuple[str, ...], int] = {}
    try:
        try:
            os.mkdir(name, _DIRECTORY_MODE, dir_fd=parent_fd)
        except FileExistsError as exc:
            raise FullC6CargoWorkspaceError("Cargo materialization destination already exists") from exc
        root_fd = os.open(name, os.O_RDONLY | directory_flag | nofollow, dir_fd=parent_fd)
        os.fchmod(root_fd, _DIRECTORY_MODE)
        opened[()] = root_fd
        projection = receipt.executor_projection
        for entry in projection:
            if entry.kind != "directory":
                continue
            parts = PurePosixPath(entry.logical_name).parts
            parent_parts = parts[:-1]
            parent_directory_fd = _materialized_directory_fd(opened, parent_parts)
            os.mkdir(parts[-1], entry.mode, dir_fd=parent_directory_fd)
            child_fd = os.open(
                parts[-1],
                os.O_RDONLY | directory_flag | nofollow,
                dir_fd=parent_directory_fd,
            )
            os.fchmod(child_fd, entry.mode)
            opened[parts] = child_fd
        payload_by_name = dict(zip(_file_names(receipt), receipt._file_payloads, strict=True))
        for entry in projection:
            if entry.kind != "file":
                continue
            parts = PurePosixPath(entry.logical_name).parts
            parent_directory_fd = _materialized_directory_fd(opened, parts[:-1])
            file_fd = os.open(
                parts[-1],
                os.O_WRONLY | os.O_CREAT | os.O_EXCL | nofollow,
                entry.mode,
                dir_fd=parent_directory_fd,
            )
            try:
                payload = payload_by_name[entry.logical_name]
                view = memoryview(payload)
                while view:
                    written = os.write(file_fd, view)
                    if written <= 0:
                        raise FullC6CargoWorkspaceError("Cargo materialization write failed")
                    view = view[written:]
                os.fchmod(file_fd, entry.mode)
                observed = os.fstat(file_fd)
                if (
                    observed.st_size != entry.size
                    or hashlib.sha256(payload).hexdigest() != entry.sha256
                ):
                    raise FullC6CargoWorkspaceError("Cargo materialization bytes are stale")
            finally:
                os.close(file_fd)
        return projection
    except OSError as exc:
        raise FullC6CargoWorkspaceError("Cargo dependency workspace materialization failed") from exc
    finally:
        for parts, directory_fd in sorted(opened.items(), key=lambda item: len(item[0]), reverse=True):
            if root_fd is not None and directory_fd == root_fd and parts == ():
                continue
            os.close(directory_fd)
        if root_fd is not None:
            os.close(root_fd)
        os.close(parent_fd)


def _capture_stable_vendor_tree(root: Path) -> _CapturedTree:
    first = _capture_vendor_tree_once(root)
    second = _capture_vendor_tree_once(root)
    if first != second:
        raise FullC6CargoWorkspaceError("Cargo vendor tree changed during capture")
    return first


def _capture_cargo_lock_payload(
    path: Path,
    cargo_sources: CargoSourcesIdentity,
) -> bytes:
    """Read the exact already-identified Cargo.lock through a no-follow fd."""
    try:
        absolute = path.absolute()
        name = absolute.name
        _validate_segment(name)
        parent_fd = _open_directory_path_no_follow(absolute.parent)
        try:
            observed = os.stat(name, dir_fd=parent_fd, follow_symlinks=False)
            if (
                not stat.S_ISREG(observed.st_mode)
                or stat.S_ISLNK(observed.st_mode)
                or observed.st_nlink != 1
                or observed.st_uid != os.geteuid()
                or observed.st_size <= 0
                or observed.st_size > MAX_FULL_C6_CARGO_MANIFEST_BYTES
            ):
                raise FullC6CargoWorkspaceError(
                    "Cargo.lock is not an owner-owned unaliased regular file"
                )
            payload = _read_member_bytes(parent_fd, name, observed)
        finally:
            os.close(parent_fd)
    except FullC6CargoWorkspaceError:
        raise
    except OSError as exc:
        raise FullC6CargoWorkspaceError("Cargo.lock could not be captured safely") from exc
    expected = cargo_sources.lock_file
    if (
        expected.executable
        or expected.size != len(payload)
        or not hmac.compare_digest(
            expected.sha256,
            hashlib.sha256(payload).hexdigest(),
        )
    ):
        raise FullC6CargoWorkspaceError("Cargo.lock retained bytes differ from identity")
    return payload


def _capture_vendor_tree_once(root: Path) -> _CapturedTree:
    directory_flag = getattr(os, "O_DIRECTORY", 0)
    nofollow = getattr(os, "O_NOFOLLOW", 0)
    if not directory_flag or not nofollow:
        raise FullC6CargoWorkspaceError("no-follow directory operations are unavailable")
    try:
        root_fd = _open_directory_path_no_follow(root)
    except OSError as exc:
        raise FullC6CargoWorkspaceError("Cargo vendor root could not be opened safely") from exc
    try:
        opened = os.fstat(root_fd)
        if (
            not stat.S_ISDIR(opened.st_mode)
            or opened.st_uid != os.geteuid()
            or stat.S_IMODE(opened.st_mode) not in {0o700, 0o755}
        ):
            raise FullC6CargoWorkspaceError("Cargo vendor root identity changed")
        entries: list[FullC6CargoWorkspaceEntry] = [
            FullC6CargoWorkspaceEntry(
                logical_name="vendor",
                kind="directory",
                sha256=None,
                size=0,
                mode=_DIRECTORY_MODE,
            )
        ]
        payloads: dict[str, bytes] = {}
        aliases = {"vendor"}
        inode_keys: set[tuple[int, int]] = set()
        total_bytes = [0]
        _walk_vendor_directory(
            root_fd,
            relative=PurePosixPath(),
            entries=entries,
            payloads=payloads,
            aliases=aliases,
            inode_keys=inode_keys,
            total_bytes=total_bytes,
        )
        after = os.fstat(root_fd)
        if (opened.st_dev, opened.st_ino) != (after.st_dev, after.st_ino):
            raise FullC6CargoWorkspaceError("Cargo vendor root identity changed")
    finally:
        os.close(root_fd)
    canonical = tuple(sorted(entries, key=lambda item: (item.logical_name, item.kind)))
    if len(canonical) > MAX_FULL_C6_CARGO_TREE_ENTRIES:
        raise FullC6CargoWorkspaceError("Cargo vendor tree entry count exceeds bound")
    file_names = _file_names_from_entries(canonical)
    if len(file_names) > MAX_FULL_C6_CARGO_FILES:
        raise FullC6CargoWorkspaceError("Cargo vendor file count exceeds bound")
    file_payloads = tuple(payloads[name] for name in file_names)
    if sum(len(item) for item in file_payloads) > MAX_FULL_C6_CARGO_TOTAL_BYTES:
        raise FullC6CargoWorkspaceError("Cargo vendor tree byte count exceeds bound")
    return _CapturedTree(entries=canonical, payloads=file_payloads)


def _walk_vendor_directory(
    directory_fd: int,
    *,
    relative: PurePosixPath,
    entries: list[FullC6CargoWorkspaceEntry],
    payloads: dict[str, bytes],
    aliases: set[str],
    inode_keys: set[tuple[int, int]],
    total_bytes: list[int],
) -> None:
    try:
        scanned: list[os.DirEntry[str]] = []
        with os.scandir(directory_fd) as iterator:
            for child in iterator:
                if len(scanned) >= MAX_FULL_C6_CARGO_TREE_ENTRIES:
                    raise FullC6CargoWorkspaceError(
                        "Cargo vendor directory entry count exceeds bound"
                    )
                scanned.append(child)
        scanned.sort(key=lambda item: item.name)
    except OSError as exc:
        raise FullC6CargoWorkspaceError("Cargo vendor directory could not be scanned") from exc
    local_aliases: set[str] = set()
    for child in scanned:
        name = child.name
        _validate_segment(name)
        alias = unicodedata.normalize("NFC", name).casefold()
        if alias in local_aliases:
            raise FullC6CargoWorkspaceError("Cargo vendor tree contains a path alias")
        local_aliases.add(alias)
        child_relative = relative / name
        if len(child_relative.parts) > MAX_FULL_C6_CARGO_DEPTH:
            raise FullC6CargoWorkspaceError("Cargo vendor tree exceeds depth bound")
        logical_name = (PurePosixPath("vendor") / child_relative).as_posix()
        logical_alias = unicodedata.normalize("NFC", logical_name).casefold()
        if logical_alias in aliases:
            raise FullC6CargoWorkspaceError("Cargo vendor tree contains a path alias")
        aliases.add(logical_alias)
        if _is_caller_cargo_config(child_relative):
            raise FullC6CargoWorkspaceError("caller-provided .cargo/config is forbidden")
        try:
            observed = child.stat(follow_symlinks=False)
        except OSError as exc:
            raise FullC6CargoWorkspaceError("Cargo vendor member could not be inspected") from exc
        if stat.S_ISLNK(observed.st_mode):
            raise FullC6CargoWorkspaceError("Cargo vendor tree contains a symlink")
        if stat.S_ISDIR(observed.st_mode):
            if (
                stat.S_IMODE(observed.st_mode) != _DIRECTORY_MODE
                or observed.st_uid != os.geteuid()
            ):
                raise FullC6CargoWorkspaceError("Cargo vendor directory mode is noncanonical")
            if len(entries) >= MAX_FULL_C6_CARGO_TREE_ENTRIES:
                raise FullC6CargoWorkspaceError("Cargo vendor tree entry count exceeds bound")
            entries.append(
                FullC6CargoWorkspaceEntry(
                    logical_name=logical_name,
                    kind="directory",
                    sha256=None,
                    size=0,
                    mode=_DIRECTORY_MODE,
                )
            )
            child_fd = os.open(
                name,
                os.O_RDONLY | getattr(os, "O_DIRECTORY", 0) | getattr(os, "O_NOFOLLOW", 0),
                dir_fd=directory_fd,
            )
            try:
                actual = os.fstat(child_fd)
                if (observed.st_dev, observed.st_ino) != (actual.st_dev, actual.st_ino):
                    raise FullC6CargoWorkspaceError("Cargo vendor directory changed")
                _walk_vendor_directory(
                    child_fd,
                    relative=child_relative,
                    entries=entries,
                    payloads=payloads,
                    aliases=aliases,
                    inode_keys=inode_keys,
                    total_bytes=total_bytes,
                )
            finally:
                os.close(child_fd)
            continue
        if not stat.S_ISREG(observed.st_mode):
            raise FullC6CargoWorkspaceError("Cargo vendor tree contains a special file")
        if observed.st_uid != os.geteuid():
            raise FullC6CargoWorkspaceError("Cargo vendor file owner is invalid")
        if observed.st_nlink != 1:
            raise FullC6CargoWorkspaceError("Cargo vendor tree contains a hardlink")
        inode_key = (observed.st_dev, observed.st_ino)
        if inode_key in inode_keys:
            raise FullC6CargoWorkspaceError("Cargo vendor file inode is reused")
        inode_keys.add(inode_key)
        mode = stat.S_IMODE(observed.st_mode)
        if mode not in _FILE_MODES:
            raise FullC6CargoWorkspaceError("Cargo vendor file mode is noncanonical")
        if not 0 <= observed.st_size <= MAX_FULL_C6_CARGO_FILE_BYTES:
            raise FullC6CargoWorkspaceError("Cargo vendor file exceeds byte bound")
        if len(payloads) >= MAX_FULL_C6_CARGO_FILES:
            raise FullC6CargoWorkspaceError("Cargo vendor file count exceeds bound")
        if total_bytes[0] + observed.st_size > MAX_FULL_C6_CARGO_TOTAL_BYTES:
            raise FullC6CargoWorkspaceError("Cargo vendor tree byte count exceeds bound")
        payload = _read_member_bytes(directory_fd, name, observed)
        total_bytes[0] += len(payload)
        if len(entries) >= MAX_FULL_C6_CARGO_TREE_ENTRIES:
            raise FullC6CargoWorkspaceError("Cargo vendor tree entry count exceeds bound")
        entries.append(
            FullC6CargoWorkspaceEntry(
                logical_name=logical_name,
                kind="file",
                sha256=hashlib.sha256(payload).hexdigest(),
                size=len(payload),
                mode=mode,
            )
        )
        payloads[logical_name] = payload


def _read_member_bytes(parent_fd: int, name: str, expected: os.stat_result) -> bytes:
    try:
        file_fd = os.open(
            name,
            os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0),
            dir_fd=parent_fd,
        )
    except OSError as exc:
        raise FullC6CargoWorkspaceError("Cargo vendor file could not be opened safely") from exc
    try:
        before = os.fstat(file_fd)
        if (
            not stat.S_ISREG(before.st_mode)
            or before.st_nlink != 1
            or (before.st_dev, before.st_ino) != (expected.st_dev, expected.st_ino)
            or before.st_size != expected.st_size
        ):
            raise FullC6CargoWorkspaceError("Cargo vendor file identity changed")
        chunks: list[bytes] = []
        total = 0
        while True:
            chunk = os.read(file_fd, min(1024 * 1024, MAX_FULL_C6_CARGO_FILE_BYTES + 1 - total))
            if not chunk:
                break
            chunks.append(chunk)
            total += len(chunk)
            if total > MAX_FULL_C6_CARGO_FILE_BYTES:
                raise FullC6CargoWorkspaceError("Cargo vendor file exceeds byte bound")
        after = os.fstat(file_fd)
        if (
            (before.st_dev, before.st_ino, before.st_size, before.st_mtime_ns)
            != (after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns)
            or total != before.st_size
        ):
            raise FullC6CargoWorkspaceError("Cargo vendor file changed during capture")
        return b"".join(chunks)
    finally:
        os.close(file_fd)


def _validate_packages(
    sources: tuple[CargoSourceIdentity, ...],
    entries: tuple[FullC6CargoWorkspaceEntry, ...],
    payloads: dict[str, bytes],
) -> tuple[str, tuple[FullC6CargoPackageReceipt, ...]]:
    root_directories = {
        PurePosixPath(item.logical_name).name
        for item in entries
        if item.kind == "directory" and len(PurePosixPath(item.logical_name).parts) == 2
    }
    default_directories = _cargo_vendor_directories(
        sources,
        layout=FULL_C6_CARGO_LAYOUT_DEFAULT,
    )
    versioned_directories = _cargo_vendor_directories(
        sources,
        layout=FULL_C6_CARGO_LAYOUT_VERSIONED,
    )
    if root_directories == set(default_directories):
        vendor_layout = FULL_C6_CARGO_LAYOUT_DEFAULT
        expected_directories = default_directories
    elif root_directories == set(versioned_directories):
        vendor_layout = FULL_C6_CARGO_LAYOUT_VERSIONED
        expected_directories = versioned_directories
    else:
        raise FullC6CargoWorkspaceError(
            "Cargo vendor package set or directory layout differs from Cargo.lock"
        )
    expected_directory_set = set(expected_directories)
    if any(
        len(PurePosixPath(item.logical_name).parts) > 1
        and PurePosixPath(item.logical_name).parts[1] not in expected_directory_set
        for item in entries
    ):
        raise FullC6CargoWorkspaceError("Cargo vendor tree contains an extra package member")
    receipts: list[FullC6CargoPackageReceipt] = []
    for source, directory in zip(sources, expected_directories, strict=True):
        prefix = PurePosixPath("vendor") / directory
        checksum_name = (prefix / ".cargo-checksum.json").as_posix()
        checksum_payload = payloads.get(checksum_name)
        if checksum_payload is None or len(checksum_payload) > MAX_FULL_C6_CARGO_CHECKSUM_BYTES:
            raise FullC6CargoWorkspaceError("Cargo vendor checksum manifest is missing")
        package_checksum, declared_files = _parse_checksum_manifest(checksum_payload)
        if package_checksum != source.checksum:
            raise FullC6CargoWorkspaceError("Cargo vendor package checksum differs from Cargo.lock")
        actual_files = {
            PurePosixPath(name).relative_to(prefix).as_posix()
            for name in payloads
            if PurePosixPath(name).is_relative_to(prefix) and name != checksum_name
        }
        if set(declared_files) != actual_files:
            raise FullC6CargoWorkspaceError("Cargo vendor checksum file set is incomplete")
        for relative_name, digest in declared_files.items():
            logical_name = (prefix / PurePosixPath(relative_name)).as_posix()
            if not hmac.compare_digest(hashlib.sha256(payloads[logical_name]).hexdigest(), digest):
                raise FullC6CargoWorkspaceError("Cargo vendor file checksum differs")
        cargo_toml = (prefix / "Cargo.toml").as_posix()
        manifest_payload = payloads.get(cargo_toml)
        if manifest_payload is None:
            raise FullC6CargoWorkspaceError("Cargo vendor Cargo.toml is missing")
        manifest = _parse_package_manifest(manifest_payload, source)
        metadata = {cargo_toml}
        for name in payloads:
            candidate = PurePosixPath(name)
            if candidate.is_relative_to(prefix) and _is_license_basename(candidate.name):
                metadata.add(name)
        license_file = manifest.get("license-file")
        if license_file is not None:
            if type(license_file) is not str:
                raise FullC6CargoWorkspaceError("Cargo package license-file is invalid")
            _validate_package_relative_name(license_file)
            logical_license = (prefix / PurePosixPath(license_file)).as_posix()
            if logical_license not in payloads:
                raise FullC6CargoWorkspaceError("Cargo package license-file is missing")
            metadata.add(logical_license)
        file_set_sha256 = _sha256(
            {
                "domain": "rextio.full-c6-cargo-package-file-set.v1",
                "files": [
                    {"path": name, "sha256": declared_files[name]}
                    for name in sorted(declared_files, key=str.casefold)
                ],
            }
        )
        receipts.append(
            FullC6CargoPackageReceipt(
                package=source,
                directory=directory,
                checksum_manifest_sha256=hashlib.sha256(checksum_payload).hexdigest(),
                file_set_sha256=file_set_sha256,
                cargo_toml=cargo_toml,
                metadata_files=tuple(sorted(metadata, key=str.casefold)),
            )
        )
    return (
        vendor_layout,
        tuple(
            sorted(
                receipts,
                key=lambda item: (
                    item.package.name,
                    item.package.version,
                    item.package.source,
                    item.package.checksum,
                ),
            )
        ),
    )


def _cargo_vendor_directories(
    sources: tuple[CargoSourceIdentity, ...],
    *,
    layout: str,
) -> tuple[str, ...]:
    """Return one closed Cargo 1.93 vendor directory profile."""
    if layout not in {
        FULL_C6_CARGO_LAYOUT_DEFAULT,
        FULL_C6_CARGO_LAYOUT_VERSIONED,
    }:
        raise FullC6CargoWorkspaceError("Cargo vendor directory layout is unsupported")
    name_counts: dict[str, int] = {}
    for source in sources:
        name_counts[source.name] = name_counts.get(source.name, 0) + 1
    directories = tuple(
        (
            f"{source.name}-{source.version}"
            if layout == FULL_C6_CARGO_LAYOUT_VERSIONED or name_counts[source.name] > 1
            else source.name
        )
        for source in sources
    )
    if len(set(directories)) != len(directories):
        raise FullC6CargoWorkspaceError("Cargo vendor package directories are ambiguous")
    for directory in directories:
        if _PACKAGE_DIRECTORY.fullmatch(directory) is None:
            raise FullC6CargoWorkspaceError("Cargo vendor package directory is invalid")
    return directories


def _parse_checksum_manifest(payload: bytes) -> tuple[str, dict[str, str]]:
    try:
        document = json.loads(
            payload.decode("utf-8"),
            object_pairs_hook=_strict_json_object,
        )
    except (UnicodeDecodeError, json.JSONDecodeError, ValueError) as exc:
        raise FullC6CargoWorkspaceError("Cargo vendor checksum manifest is invalid") from exc
    if not isinstance(document, dict) or set(document) != {"files", "package"}:
        raise FullC6CargoWorkspaceError("Cargo vendor checksum manifest has an open schema")
    package = document["package"]
    files = document["files"]
    if type(package) is not str or _SHA256.fullmatch(package) is None or not isinstance(files, dict):
        raise FullC6CargoWorkspaceError("Cargo vendor checksum manifest values are invalid")
    if not files or len(files) > MAX_FULL_C6_CARGO_FILES:
        raise FullC6CargoWorkspaceError("Cargo vendor checksum file count is outside bound")
    canonical: dict[str, str] = {}
    aliases: set[str] = set()
    for name, digest in files.items():
        if type(name) is not str or type(digest) is not str or _SHA256.fullmatch(digest) is None:
            raise FullC6CargoWorkspaceError("Cargo vendor checksum file identity is invalid")
        _validate_package_relative_name(name)
        alias = unicodedata.normalize("NFC", name).casefold()
        if alias in aliases or name == ".cargo-checksum.json":
            raise FullC6CargoWorkspaceError("Cargo vendor checksum paths contain an alias")
        aliases.add(alias)
        canonical[name] = digest
    return package, canonical


def _parse_package_manifest(payload: bytes, source: CargoSourceIdentity) -> dict[str, object]:
    if len(payload) > MAX_FULL_C6_CARGO_MANIFEST_BYTES:
        raise FullC6CargoWorkspaceError("Cargo vendor Cargo.toml exceeds byte bound")
    try:
        document = tomllib.loads(payload.decode("utf-8"))
    except (UnicodeDecodeError, tomllib.TOMLDecodeError) as exc:
        raise FullC6CargoWorkspaceError("Cargo vendor Cargo.toml is invalid") from exc
    package = document.get("package")
    if not isinstance(package, dict):
        raise FullC6CargoWorkspaceError("Cargo vendor Cargo.toml lacks [package]")
    if package.get("name") != source.name or package.get("version") != source.version:
        raise FullC6CargoWorkspaceError("Cargo vendor Cargo.toml identity differs from Cargo.lock")
    return package


def _validate_receipt_shape(receipt: FullC6CargoDependencyWorkspaceReceipt) -> None:
    if (
        receipt.domain != FULL_C6_CARGO_WORKSPACE_DOMAIN
        or receipt.scope != "owner-prepared-cargo-vendor-locked-crates-io-v1"
        or receipt.complete_for_scope is not True
        or receipt.authorizes_build
        or receipt.authorizes_distribution
    ):
        raise ValueError("Full C6 Cargo workspace authority posture is invalid")
    if type(receipt.cargo_sources) is not CargoSourcesIdentity:
        raise TypeError("Full C6 Cargo source identity is invalid")
    lock_identity = receipt.cargo_sources.lock_file
    if (
        type(receipt._cargo_lock_payload) is not bytes
        or not receipt._cargo_lock_payload
        or len(receipt._cargo_lock_payload) > MAX_FULL_C6_CARGO_MANIFEST_BYTES
        or lock_identity.executable
        or lock_identity.size != len(receipt._cargo_lock_payload)
        or not hmac.compare_digest(
            lock_identity.sha256,
            hashlib.sha256(receipt._cargo_lock_payload).hexdigest(),
        )
    ):
        raise ValueError("Full C6 Cargo retained Cargo.lock bytes are stale")
    if (
        type(receipt.packages) is not tuple
        or not receipt.packages
        or any(type(item) is not FullC6CargoPackageReceipt for item in receipt.packages)
        or receipt.packages
        != tuple(
            sorted(
                receipt.packages,
                key=lambda item: (
                    item.package.name,
                    item.package.version,
                    item.package.source,
                    item.package.checksum,
                ),
            )
        )
    ):
        raise ValueError("Full C6 Cargo package receipts are invalid")
    if tuple(item.package for item in receipt.packages) != receipt.cargo_sources.packages:
        raise ValueError("Full C6 Cargo packages differ from Cargo.lock")
    expected_directories = _cargo_vendor_directories(
        receipt.cargo_sources.packages,
        layout=receipt.vendor_layout,
    )
    if tuple(item.directory for item in receipt.packages) != expected_directories:
        raise ValueError("Full C6 Cargo package layout differs from its receipt")
    if (
        type(receipt.vendor_entries) is not tuple
        or not receipt.vendor_entries
        or any(type(item) is not FullC6CargoWorkspaceEntry for item in receipt.vendor_entries)
        or receipt.vendor_entries
        != tuple(sorted(receipt.vendor_entries, key=lambda item: (item.logical_name, item.kind)))
        or _vendor_tree_digest(receipt.vendor_entries) != receipt.vendor_tree_sha256
    ):
        raise ValueError("Full C6 Cargo vendor tree receipt is invalid")
    if (
        type(receipt.executor_config) is not FullC6CargoWorkspaceEntry
        or receipt.executor_config.logical_name != FULL_C6_CARGO_EXECUTOR_CONFIG
        or receipt.executor_config.sha256
        != hashlib.sha256(FULL_C6_CARGO_EXECUTOR_CONFIG_BYTES).hexdigest()
        or receipt.executor_config.size != len(FULL_C6_CARGO_EXECUTOR_CONFIG_BYTES)
        or receipt.executor_config.mode != 0o644
    ):
        raise ValueError("Full C6 Cargo executor config identity is invalid")
    if (
        type(receipt.metadata_files) is not tuple
        or receipt.metadata_files != tuple(sorted(receipt.metadata_files, key=str.casefold))
        or len({item.casefold() for item in receipt.metadata_files})
        != len(receipt.metadata_files)
    ):
        raise ValueError("Full C6 Cargo metadata identities are invalid")
    file_entries = tuple(item for item in receipt.executor_projection if item.kind == "file")
    if (
        type(receipt._file_payloads) is not tuple
        or len(receipt._file_payloads) != len(file_entries)
        or any(type(item) is not bytes for item in receipt._file_payloads)
    ):
        raise ValueError("Full C6 Cargo retained payloads are invalid")
    for entry, payload in zip(file_entries, receipt._file_payloads, strict=True):
        if entry.size != len(payload) or entry.sha256 != hashlib.sha256(payload).hexdigest():
            raise ValueError("Full C6 Cargo retained payload bytes are stale")
    file_names = {item.logical_name for item in file_entries}
    if not set(receipt.metadata_files).issubset(file_names):
        raise ValueError("Full C6 Cargo metadata payload coverage is incomplete")


def _receipt_seal(receipt: FullC6CargoDependencyWorkspaceReceipt) -> bytes:
    return hmac.new(_SEAL_KEY, _canonical_json(receipt._payload()), hashlib.sha256).digest()


def _vendor_tree_digest(entries: tuple[FullC6CargoWorkspaceEntry, ...]) -> str:
    return _sha256(
        {
            "domain": FULL_C6_CARGO_VENDOR_TREE_DOMAIN,
            "entries": [item.to_dict() for item in entries],
        }
    )


def _file_names(receipt: FullC6CargoDependencyWorkspaceReceipt) -> tuple[str, ...]:
    return _file_names_from_entries(receipt.executor_projection)


def _file_names_from_entries(
    entries: tuple[FullC6CargoWorkspaceEntry, ...],
) -> tuple[str, ...]:
    return tuple(item.logical_name for item in entries if item.kind == "file")


def _strict_json_object(pairs: list[tuple[str, object]]) -> dict[str, object]:
    result: dict[str, object] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("duplicate JSON key")
        result[key] = value
    return result


def _validate_logical_name(value: str) -> None:
    if type(value) is not str or not value or len(value) > MAX_FULL_C6_CARGO_PATH_CHARS:
        raise ValueError("Full C6 Cargo logical path is invalid")
    posix = PurePosixPath(value)
    windows = PureWindowsPath(value)
    if posix.is_absolute() or windows.is_absolute() or bool(windows.drive):
        raise ValueError("Full C6 Cargo logical path must be relative")
    if (
        value != value.strip()
        or posix.as_posix() != value
        or "\\" in value
        or any(ord(character) < 32 for character in value)
    ):
        raise ValueError("Full C6 Cargo logical path contains unsafe characters")
    parts = posix.parts
    if not parts or any(part in {"", ".", ".."} for part in parts):
        raise ValueError("Full C6 Cargo logical path is noncanonical")
    for part in parts:
        _validate_segment(part)


def _validate_segment(value: str) -> None:
    if (
        type(value) is not str
        or not value
        or value in {".", ".."}
        or "/" in value
        or "\\" in value
        or len(value) > 255
        or value != value.strip()
        or unicodedata.normalize("NFC", value) != value
        or any(ord(character) < 32 for character in value)
    ):
        raise FullC6CargoWorkspaceError("Cargo vendor path segment is invalid")


def _validate_package_relative_name(value: str) -> None:
    try:
        _validate_logical_name(value)
    except (TypeError, ValueError, FullC6CargoWorkspaceError) as exc:
        raise FullC6CargoWorkspaceError("Cargo package-relative path is invalid") from exc
    if len(PurePosixPath(value).parts) > MAX_FULL_C6_CARGO_DEPTH - 2:
        raise FullC6CargoWorkspaceError("Cargo package-relative path exceeds depth bound")


def _is_caller_cargo_config(relative: PurePosixPath) -> bool:
    parts = relative.parts
    return len(parts) >= 2 and parts[-2] == ".cargo" and parts[-1].startswith("config")


def _is_license_basename(name: str) -> bool:
    upper = name.upper()
    return any(
        upper == prefix
        or upper.startswith(prefix + "-")
        or upper.startswith(prefix + ".")
        or upper.startswith(prefix + "_")
        for prefix in _LICENSE_BASENAMES
    )


def _open_directory_path_no_follow(path: Path) -> int:
    try:
        absolute = path.absolute()
    except OSError as exc:
        raise FullC6CargoWorkspaceError("Cargo workspace path could not be normalized") from exc
    directory_flag = getattr(os, "O_DIRECTORY", 0)
    nofollow = getattr(os, "O_NOFOLLOW", 0)
    if not directory_flag or not nofollow or not absolute.anchor:
        raise FullC6CargoWorkspaceError("no-follow directory operations are unavailable")
    current_fd = os.open(absolute.anchor, os.O_RDONLY | directory_flag | nofollow)
    try:
        for part in absolute.parts[1:]:
            _validate_segment(part)
            next_fd = os.open(
                part,
                os.O_RDONLY | directory_flag | nofollow,
                dir_fd=current_fd,
            )
            os.close(current_fd)
            current_fd = next_fd
        return current_fd
    except OSError as exc:
        os.close(current_fd)
        raise FullC6CargoWorkspaceError(
            "Cargo workspace path contains a missing or linked component"
        ) from exc
    except Exception:
        os.close(current_fd)
        raise


def _materialized_directory_fd(
    opened: dict[tuple[str, ...], int],
    parts: tuple[str, ...],
) -> int:
    try:
        return opened[parts]
    except KeyError as exc:
        raise FullC6CargoWorkspaceError("Cargo materialization directory projection is incomplete") from exc


def _canonical_json(value: object) -> bytes:
    return json.dumps(
        value,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=True,
    ).encode("ascii")


def _sha256(value: object) -> str:
    return hashlib.sha256(_canonical_json(value)).hexdigest()


