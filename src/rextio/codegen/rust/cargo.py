"""Rendering of Cargo/pyproject manifests for the generated Rust project."""

from __future__ import annotations


def render_cargo_toml(package_name: str = "rextio_generated_native", include_jit: bool = False) -> str:
    """Render the Cargo.toml for the generated native extension crate."""
    jit_dependencies = (
        'cranelift-codegen = "0.121"\n'
        'cranelift-frontend = "0.121"\n'
        'cranelift-jit = "0.121"\n'
        'cranelift-module = "0.121"\n'
        if include_jit
        else ""
    )
    return f"""# Generated by Rextio. Do not edit manually.

[package]
name = "{package_name}"
version = "0.1.0"
edition = "2021"

[lib]
name = "_rextio_native"
crate-type = ["cdylib"]

# Preserve Python integer semantics: i64 arithmetic that overflows is a real error
# (Python ints are arbitrary precision), so overflow must panic — PyO3 converts the
# panic into a Python exception — instead of silently wrapping in release builds.
[profile.release]
overflow-checks = true

[dependencies]
base64 = "0.22"
chrono = "0.4"
log = "0.4"
pyo3 = {{ version = "0.22", features = ["extension-module"] }}
serde_json = "1"
sha2 = "0.10"
{jit_dependencies}"""


def render_importable_cargo_toml(package_name: str = "rextio_generated_rust") -> str:
    """Render the Cargo.toml for the Rust-importable crate."""
    return f"""# Generated by Rextio. Do not edit manually.

[package]
name = "{package_name}"
version = "0.1.0"
edition = "2021"

[lib]
name = "{package_name.replace("-", "_")}"

# Integer overflow is an error (Python ints are arbitrary precision), so it must
# panic rather than silently wrap, even in release builds.
[profile.release]
overflow-checks = true

[dependencies]
base64 = "0.22"
chrono = "0.4"
log = "0.4"
serde_json = "1"
sha2 = "0.10"
"""


def render_pyproject_toml() -> str:
    """Render the pyproject.toml for the maturin/PyO3 build."""
    return """# Generated by Rextio. Do not edit manually.

[build-system]
requires = ["maturin>=1.0,<2.0"]
build-backend = "maturin"

[project]
name = "rextio-generated-native"
version = "0.1.0"
requires-python = ">=3.11"
"""


def render_cargo_config_toml() -> str:
    """Render the Cargo config.toml for the generated build."""
    return """# Generated by Rextio. Do not edit manually.

[target.aarch64-apple-darwin]
rustflags = ["-C", "link-arg=-undefined", "-C", "link-arg=dynamic_lookup"]

[target.x86_64-apple-darwin]
rustflags = ["-C", "link-arg=-undefined", "-C", "link-arg=dynamic_lookup"]
"""
