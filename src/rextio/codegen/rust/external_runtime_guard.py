        "fn __rextio_external_record_path_is_safe(path: &str) -> bool {",
        "    !path.is_empty()",
        "        && path.len() <= __REXTIO_EXTERNAL_RECORD_MAX_FIELD_BYTES",
        "        && !path.starts_with('/')",
        "        && !path.contains('\\\\')",
        "        && !path",
