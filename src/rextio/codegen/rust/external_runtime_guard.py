        "        if parts.peek().is_some() {",
        "            directory = __rextio_open_external_at(&directory, part, true)?;",
        "            continue;",
        "        }",
        "        let mut source = __rextio_open_external_at(&directory, part, false)?;",
        "        let before = source",
        "            .metadata()",
        "            .map_err(|_| __rextio_external_guard_error())?;",
        "        if !before.is_file()",
        "            || before.nlink() != 1",
        "            || minimum_size > maximum_size",
        "            || before.len() < minimum_size",
        "            || before.len() > maximum_size",
        "        {",
        "            return Err(__rextio_external_guard_error());",
        "        }",
        "        let capacity = usize::try_from(before.len())",
        "            .map_err(|_| __rextio_external_guard_error())?;",
        "        let mut bytes = Vec::with_capacity(capacity);",
        "        source",
        "            .by_ref()",
        "            .take(maximum_size + 1)",
        "            .read_to_end(&mut bytes)",
        "            .map_err(|_| __rextio_external_guard_error())?;",
        "        let after = source",
        "            .metadata()",
        "            .map_err(|_| __rextio_external_guard_error())?;",
        "        if bytes.len() != capacity",
        "            || before.dev() != after.dev()",
        "            || before.ino() != after.ino()",
        "            || before.nlink() != after.nlink()",
        "            || before.len() != after.len()",
        "            || before.mtime() != after.mtime()",
        "            || before.mtime_nsec() != after.mtime_nsec()",
        "            || before.ctime() != after.ctime()",
        "            || before.ctime_nsec() != after.ctime_nsec()",
