        "    }",
        "    *row_count += 1;",
        "    visit(&fields[0], &fields[1], &fields[2])?;",
        "    fields.clear();",
        "    Ok(())",
        "}",
        "",
        "fn __rextio_parse_external_record<F>(bytes: &[u8], mut visit: F) -> PyResult<()> ",
        "where",
        "    F: FnMut(&str, &str, &str) -> PyResult<()>,",
        "{",
        "    if bytes.is_empty() || bytes.len() > __REXTIO_EXTERNAL_RECORD_MAX_BYTES as usize {",
        "        return Err(__rextio_external_guard_error());",
        "    }",
        "    let mut index = 0usize;",
        "    let mut field = Vec::new();",
        "    let mut fields = Vec::with_capacity(3);",
        "    let mut row_count = 0usize;",
        "    let mut in_quotes = false;",
        "    let mut after_quote = false;",
        "    let mut at_field_start = true;",
        "    while index < bytes.len() {",
        "        let byte = bytes[index];",
        "        if in_quotes {",
        "            if byte == b'\"' {",
        "                if index + 1 < bytes.len() && bytes[index + 1] == b'\"' {",
        "                    if field.len() >= __REXTIO_EXTERNAL_RECORD_MAX_FIELD_BYTES {",
        "                        return Err(__rextio_external_guard_error());",
        "                    }",
        "                    field.push(b'\"');",
        "                    index += 2;",
        "                    continue;",
        "                }",
        "                in_quotes = false;",
        "                after_quote = true;",
        "                index += 1;",
        "                continue;",
        "            }",
        "            if field.len() >= __REXTIO_EXTERNAL_RECORD_MAX_FIELD_BYTES {",
        "                return Err(__rextio_external_guard_error());",
        "            }",
        "            field.push(byte);",
        "            index += 1;",
        "            continue;",
        "        }",
        "        if after_quote {",
        "            if byte == b',' {",
        "                __rextio_finish_external_record_field(&mut fields, &mut field)?;",
        "                after_quote = false;",
        "                at_field_start = true;",
        "                index += 1;",
        "                continue;",
        "            }",
        "            if byte == b'\\n' || byte == b'\\r' {",
        "                if byte == b'\\r'",
        "                    && (index + 1 >= bytes.len() || bytes[index + 1] != b'\\n')",
        "                {",
        "                    return Err(__rextio_external_guard_error());",
        "                }",
        "                __rextio_finish_external_record_row(",
        "                    &mut fields, &mut field, &mut row_count, &mut visit,",
        "                )?;",
        "                after_quote = false;",
        "                at_field_start = true;",
        "                index += if byte == b'\\r' { 2 } else { 1 };",
        "                continue;",
        "            }",
        "            return Err(__rextio_external_guard_error());",
        "        }",
        "        if byte == b'\"' {",
        "            if !at_field_start {",
        "                return Err(__rextio_external_guard_error());",
        "            }",
        "            in_quotes = true;",
        "            at_field_start = false;",
        "            index += 1;",
        "        } else if byte == b',' {",
        "            __rextio_finish_external_record_field(&mut fields, &mut field)?;",
        "            at_field_start = true;",
        "            index += 1;",
        "        } else if byte == b'\\n' || byte == b'\\r' {",
        "            if byte == b'\\r'",
        "                && (index + 1 >= bytes.len() || bytes[index + 1] != b'\\n')",
        "            {",
        "                return Err(__rextio_external_guard_error());",
        "            }",
        "            __rextio_finish_external_record_row(",
        "                &mut fields, &mut field, &mut row_count, &mut visit,",
        "            )?;",
        "            at_field_start = true;",
        "            index += if byte == b'\\r' { 2 } else { 1 };",
        "        } else {",
        "            if field.len() >= __REXTIO_EXTERNAL_RECORD_MAX_FIELD_BYTES {",
        "                return Err(__rextio_external_guard_error());",
        "            }",
        "            field.push(byte);",
        "            at_field_start = false;",
        "            index += 1;",
        "        }",
        "    }",
        "    if in_quotes {",
        "        return Err(__rextio_external_guard_error());",
        "    }",
        "    if !fields.is_empty() || !field.is_empty() || !at_field_start || after_quote {",
        "        __rextio_finish_external_record_row(",
        "            &mut fields, &mut field, &mut row_count, &mut visit,",
        "        )?;",
        "    }",
        "    if row_count == 0 {",
        "        return Err(__rextio_external_guard_error());",
        "    }",
        "    Ok(())",
        "}",
