        "const __REXTIO_EXTERNAL_METADATA_MAX_ROWS: usize = 4096;",
        "const __REXTIO_EXTERNAL_METADATA_MAX_LINE_BYTES: usize = 8192;",
        "const __REXTIO_EXTERNAL_METADATA_MAX_VALUE_BYTES: usize = 4096;",
        "",
        "fn __rextio_verify_external_metadata(",
        "    bytes: &[u8],",
        "    expected_name: &str,",
        "    expected_version: &str,",
