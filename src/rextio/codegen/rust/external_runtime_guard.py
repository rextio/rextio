        "            return Err(__rextio_external_guard_error());",
        "        }",
        "        return Ok(bytes);",
        "    }",
        "    Err(__rextio_external_guard_error())",
        "}",
        "",
        '#[cfg(not(any(target_os = "linux", target_os = "macos")))]',
