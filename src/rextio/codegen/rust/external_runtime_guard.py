        "                return Err(__rextio_external_guard_error());",
        "            }",
        "            version_seen = true;",
        "        }",
        "    }",
        "    if !name_seen || !version_seen {",
        "        return Err(__rextio_external_guard_error());",
        "    }",
        "    Ok(())",
        "}",
