        "    if fields.len() >= 3 || field.len() > __REXTIO_EXTERNAL_RECORD_MAX_FIELD_BYTES {",
        "        return Err(__rextio_external_guard_error());",
        "    }",
        "    let value = std::str::from_utf8(field)",
        "        .map_err(|_| __rextio_external_guard_error())?",
        "        .to_owned();",
        "    fields.push(value);",
        "    field.clear();",
        "    Ok(())",
        "}",
        "",
        "fn __rextio_finish_external_record_row<F>(",
