        ") -> PyResult<Vec<u8>> {",
        "    use std::io::Read as _;",
        "    use std::os::unix::fs::MetadataExt as _;",
        "    let mut directory = __rextio_open_external_root(root)?;",
        "    let mut parts = member.split('/').peekable();",
