from __future__ import annotations

GENERATED_HEADER = "// Generated by Rextio. Do not edit manually."


def render_pyo3_module(functions: list[tuple[str, str]], module_name: str = "_rextio_native") -> str:
    lines = [
        GENERATED_HEADER,
        "",
        "use pyo3::prelude::*;",
        "use pyo3::types::{PyDict, PyTuple};",
        "use base64::Engine;",
        "use sha2::Digest;",
        "use std::collections::HashMap;",
        "use std::collections::HashSet;",
        "",
        "fn rextio_call_python_runtime(",
        "    py: Python<'_>,",
        "    module_name: &str,",
        "    attr_path: &[&str],",
        "    args: &Bound<'_, PyTuple>,",
        "    kwargs: Option<&Bound<'_, PyDict>>,",
        ") -> PyResult<PyObject> {",
        "    let module = PyModule::import_bound(py, module_name)?;",
        "    let mut target = module.getattr(attr_path[0])?;",
        "    for attr in &attr_path[1..] {",
        "        target = target.getattr(*attr)?;",
        "    }",
        "    let value = target.call(args, kwargs)?;",
        "    Ok(value.unbind())",
        "}",
        "",
    ]
    for _rust_name, function_source in functions:
        lines.append(function_source)
        lines.append("")
    lines.extend(
        [
            "#[pymodule]",
            f"fn {module_name}(m: &Bound<'_, PyModule>) -> PyResult<()> {{",
        ]
    )
    for rust_name, _function_source in functions:
        lines.append(f"    m.add_function(wrap_pyfunction!({rust_name}, m)?)?;")
    lines.extend(
        [
            "    Ok(())",
            "}",
            "",
        ]
    )
    return "\n".join(lines)
