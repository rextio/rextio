def test_inventory_rejects_cross_registry_checksum_fallback() -> None:
    root_id = "path+file://generated#rextio_generated_native@0.1.0"
    reg_id = "registry+https://github.com/rust-lang/crates.io-index#cfg-if@1.0.0"
    source = "registry+https://github.com/rust-lang/crates.io-index"
    other = "registry+https://other.example/index"
    checksum = "baf1de4339761588bc0619e3cbc0120ee582ebb74b53b4efbf79117bd2da40fd"
    payload = {
        "packages": [
            {
                "name": "rextio_generated_native",
                "version": "0.1.0",
                "source": None,
                "id": root_id,
            },
            {
                "name": "cfg-if",
                "version": "1.0.0",
                "source": source,
                "id": reg_id,
            },
        ],
        "resolve": {
            "root": root_id,
            "nodes": [
                {"id": root_id, "dependencies": [reg_id], "features": []},
                {"id": reg_id, "dependencies": [], "features": []},
            ],
        },
    }
    # Checksum registered under a different registry must not bind.
    with pytest.raises(ArtifactEvidenceError, match="checksum"):
        _inventory_from_metadata(
            payload,
            lock_checksums={("cfg-if", "1.0.0", other): checksum},
            target_triple="aarch64-apple-darwin",
            expected_root_name="rextio_generated_native",
        )


def _duplicate_dependency_payload(count: int) -> tuple[dict[str, object], str, str, str]:
    root_id = "path+file://generated#rextio_generated_native@0.1.0"
    source = "registry+https://github.com/rust-lang/crates.io-index"
    dep_id = f"{source}#cfg-if@1.0.0"
    checksum = "baf1de4339761588bc0619e3cbc0120ee582ebb74b53b4efbf79117bd2da40fd"
    payload: dict[str, object] = {
        "packages": [
            {
                "name": "rextio_generated_native",
                "version": "0.1.0",
                "source": None,
                "id": root_id,
            },
            {
                "name": "cfg-if",
                "version": "1.0.0",
                "source": source,
                "id": dep_id,
            },
        ],
        "resolve": {
            "root": root_id,
            "nodes": [
                {"id": root_id, "dependencies": [dep_id] * count, "features": []},
                {"id": dep_id, "dependencies": [], "features": []},
            ],
        },
    }
    return payload, source, dep_id, checksum


def test_raw_dependency_reference_bound_fails_before_queue_growth(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    from rextio.build import cargo_inventory as cargo_inventory_mod

    payload, _source, _dep_id, _checksum = _duplicate_dependency_payload(5)
    monkeypatch.setattr(cargo_inventory_mod, "MAX_CARGO_EDGES", 4)

    class QueueMustNotBeConstructed:
        def __init__(self, *_args, **_kwargs) -> None:
            raise AssertionError("BFS queue must not be reached after raw-bound failure")

    monkeypatch.setattr(cargo_inventory_mod, "deque", QueueMustNotBeConstructed)
    with pytest.raises(ArtifactEvidenceError, match="reference count exceeds"):
        _inventory_from_metadata(
            payload,
            lock_checksums={},
            target_triple="aarch64-apple-darwin",
            expected_root_name="rextio_generated_native",
        )


def test_valid_duplicate_dependency_ids_are_deduplicated() -> None:
    payload, source, _dep_id, checksum = _duplicate_dependency_payload(3)
    inventory = _inventory_from_metadata(
        payload,
        lock_checksums={("cfg-if", "1.0.0", source): checksum},
        target_triple="aarch64-apple-darwin",
        expected_root_name="rextio_generated_native",
    )
    assert len(inventory.packages) == 2
    assert len(inventory.dependencies) == 1
