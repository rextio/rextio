def test_build_rust_executable_accepts_windows_exe_suffix(
    tmp_path: Path,
    monkeypatch,
) -> None:
    crate_dir = tmp_path / "crate"
    crate_dir.mkdir()
    (crate_dir / "Cargo.toml").write_text("[package]\nname = \"demo\"\n", encoding="utf-8")
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    cargo = bin_dir / "cargo"
    cargo.write_text(
        f"""#!{sys.executable}
from pathlib import Path

release = Path.cwd() / "target" / "release"
release.mkdir(parents=True, exist_ok=True)
(release / "demo-tool.exe").write_bytes(b"exe")
""",
        encoding="utf-8",
    )
    cargo.chmod(0o755)
    monkeypatch.setenv("PATH", str(bin_dir))

    result = build_rust_executable(
        crate_dir,
        tmp_path / "dist",
        "demo-tool",
        "app:main",
    )

    assert result.status == "built"
    assert Path(result.path or "") == tmp_path / "dist" / "demo-tool.exe"
    assert (tmp_path / "dist" / "demo-tool.exe").read_bytes() == b"exe"


def test_build_nuitka_standalone_executable_uses_nuitka(
    tmp_path: Path,
    monkeypatch,
) -> None:
    python_dir = _python_app(tmp_path)
    nuitka = _fake_nuitka(tmp_path)
    monkeypatch.setenv("PATH", f"{nuitka.parent}")

    result = build_nuitka_executable(
        python_dir,
        tmp_path / "dist",
        entrypoint="demo_app.cli:main",
        executable_name="demo-tool",
        mode="standalone",
    )

    assert result.status == "built"
    assert result.backend == "nuitka"
    assert result.entrypoint == "demo_app.cli:main"
    assert Path(result.path or "") == tmp_path / "dist" / "demo-tool.dist" / "demo-tool"
    assert result.command
    assert "--standalone" in result.command
    assert "--output-filename=demo-tool" in result.command
    assert (python_dir / "__rextio_executable__.py").read_text(encoding="utf-8").startswith(
        "# Generated by Rextio. Do not edit manually."
    )
    # Nuitka named the directory after the launcher script; the builder must
    # have renamed it to the documented <name>.dist layout.
    assert not (tmp_path / "dist" / "__rextio_executable__.dist").exists()


def test_build_nuitka_standalone_replaces_stale_dist_directory(
    tmp_path: Path,
    monkeypatch,
) -> None:
    # A rebuild must replace a stale dist/<name>.dist left by a previous
    # build instead of failing the rename or resolving the old binary.
    python_dir = _python_app(tmp_path)
    nuitka = _fake_nuitka(tmp_path)
    monkeypatch.setenv("PATH", f"{nuitka.parent}")
    stale = tmp_path / "dist" / "demo-tool.dist"
    stale.mkdir(parents=True)
    (stale / "demo-tool").write_text("stale binary", encoding="utf-8")

    result = build_nuitka_executable(
        python_dir,
        tmp_path / "dist",
        entrypoint="demo_app.cli:main",
        executable_name="demo-tool",
        mode="standalone",
    )

    assert result.status == "built"
    produced = tmp_path / "dist" / "demo-tool.dist" / "demo-tool"
    assert Path(result.path or "") == produced
    assert "fake nuitka" in produced.read_text(encoding="utf-8")


